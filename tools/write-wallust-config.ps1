#Requires -Version 7.0
<#
.SYNOPSIS
  Writes config\wallust\wallust.toml from config\wallust\wallust.template.toml, with this
  repo's real location filled in.

.DESCRIPTION
  wallust's [templates] targets have to be absolute paths, and this repo can be cloned
  anywhere, so the tracked file is a template with {{DESKTOPRICE_HOME}} placeholders and
  this fills them in -- same idea as komorebi.json being compiled from base.json. Run by
  install.ps1 (before its first `wallust run`); safe to run by hand any time, e.g. after
  editing the template. Only rewrites the file when the result would actually change.
  The output is gitignored.

  Exit codes: 0 = written, or already current; 1 = template missing, unusable repo path,
  or the write failed.
#>
$ErrorActionPreference = 'Stop'
$Root     = Split-Path -Parent $PSScriptRoot
$dir      = Join-Path $Root 'config\wallust'
$template = Join-Path $dir 'wallust.template.toml'
$target   = Join-Path $dir 'wallust.toml'

if (-not (Test-Path $template)) { Write-Warning "wallust template not found: $template"; exit 1 }
# The template's paths are TOML literal strings ('...'), which can't contain a single
# quote -- a repo path with one would give wallust a config it can't parse. Say so plainly
# instead of writing a broken file.
if ($Root.Contains("'")) {
    Write-Warning "The repo path contains a single quote, which wallust.toml's literal strings can't hold: $Root"
    exit 1
}

$content = "# GENERATED by tools\write-wallust-config.ps1 from wallust.template.toml -- edit the template, not this file.`n" +
           (Get-Content $template -Raw -Encoding UTF8).Replace('{{DESKTOPRICE_HOME}}', $Root)

if ((Test-Path $target) -and
    (((Get-Content $target -Raw -Encoding UTF8) -replace "`r`n", "`n") -eq ($content -replace "`r`n", "`n"))) {
    Write-Host "wallust.toml already current for $Root"
    exit 0
}
try {
    [System.IO.File]::WriteAllText($target, $content, [System.Text.UTF8Encoding]::new($false))
    Write-Host "wallust.toml written for $Root"
} catch {
    Write-Warning "couldn't write ${target}: $($_.Exception.Message)"
    exit 1
}
exit 0
